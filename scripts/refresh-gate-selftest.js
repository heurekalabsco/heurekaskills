#!/usr/bin/env node
// Exercise the autonomous-merge gate against every diff that has ever beaten it, plus the one it
// must still accept.
//
// This decides whether content reaches a public registry with no human review, so the bar is not
// "the suite is green". Two things that an earlier shell version of this file got wrong:
//
//   A refusal is only evidence if it is the RIGHT refusal. That version asserted a non-zero exit
//   and nothing else. When the gate was rebuilt, all eighteen cases still "passed" — and twelve
//   of them were being refused because their hand-written hunk headers did not match their
//   bodies, so a header-integrity check fired before the rule under test ever ran. Twelve green
//   cases proving nothing. So every case here asserts the reason text from manifest.json, and
//   the fixtures are generated by scripts/make-refresh-fixtures.js as real git output.
//
//   A gate that refuses everything satisfies every negative. PASS-real-refresh is the case that
//   fails when the gate stops being useful, and it has already caught one over-correction.
//
// Usage:  node scripts/refresh-gate-selftest.js
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const FIX = '.github/fixtures/refresh-gate';
const manifest = JSON.parse(fs.readFileSync(`${FIX}/manifest.json`, 'utf8'));

function run(fixture) {
  try {
    const out = execFileSync('node', ['scripts/is-verification-refresh.js',
      '--diff', `${FIX}/${fixture}`, '--base-dir', '.', '--run-date', manifest.runDate, '--json'],
      { encoding: 'utf8' });
    return { code: 0, verdict: JSON.parse(out) };
  } catch (e) {
    if (e.status === 1) return { code: 1, verdict: JSON.parse(e.stdout) };
    return { code: e.status ?? -1, error: (e.stdout || '') + (e.stderr || '') };
  }
}

let failed = 0;
const bad = (name, msg) => { console.log(`  FAIL ${name.padEnd(34)} ${msg}`); failed = 1; };

console.log('refresh-gate selftest');
for (const c of manifest.cases) {
  const r = run(c.fixture);
  if (r.code === -1 || r.error) { bad(c.fixture, `gate refused to decide (exit ${r.code}): ${(r.error || '').trim().slice(0, 90)}`); continue; }

  if (c.expect === 'accept') {
    if (r.verdict.refresh) console.log(`  ok   ${c.fixture.padEnd(34)} accepted`);
    else bad(c.fixture, `REJECTED — the gate can no longer fire at all:\n       · ${r.verdict.reasons.join('\n       · ')}`);
    continue;
  }

  if (r.verdict.refresh) { bad(c.fixture, `ACCEPTED — ${c.what ?? c.because}`); continue; }
  // The reason, not just the refusal. A case refused for an unrelated reason is a case that is
  // no longer testing the rule it was written for, and that must fail loudly rather than pass.
  const hit = r.verdict.reasons.some((x) => x.includes(c.because));
  if (hit) console.log(`  ok   ${c.fixture.padEnd(34)} ${c.because}`);
  else bad(c.fixture, `refused, but not for its own reason.\n       wanted: ${c.because}\n       got:    ${r.verdict.reasons.join('\n               ')}`);
}

// The fixtures must match what the generator produces from the skills as they are now. A skill
// edited later can quietly make a case vacuous — the exploit it encodes no longer applies to any
// line that exists — and a stale fixture would keep passing while testing nothing.
try {
  execFileSync('node', ['scripts/make-refresh-fixtures.js', '--check'], { encoding: 'utf8', stdio: 'pipe' });
  console.log(`  ok   ${'fixtures match the generator'.padEnd(34)} regenerating changes nothing`);
} catch (e) {
  bad('fixtures-are-current', `stale — run: node scripts/make-refresh-fixtures.js\n${(e.stdout || e.stderr || '').trim()}`);
}

console.log(failed ? '  SELFTEST FAILED' : `  all ${manifest.cases.length} cases pass`);
process.exit(failed);
